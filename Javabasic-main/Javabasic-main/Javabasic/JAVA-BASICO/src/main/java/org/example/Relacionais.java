package org.example;

public class Relacionais {
    static void main() {
        // Declaração de variáveis

        int a = 10;
        int b = 2;
        int maior;

        // Operadores aritméticos
        if (a > b) {
            maior = a;
        } else {
            maior = b;
        }

        System.out.println("O maior número é: " + maior);
    }
}


